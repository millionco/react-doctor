import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { describe, expect, it } from "vite-plus/test";
import { runRule } from "../../../test-utils/run-rule.js";
import contract from "../../utils/declared-gatsby-v1-provider-contract.json";
import { noImgWithoutDimensions } from "./no-img-without-dimensions.js";

const cardPath = "src/components/IllustratedCard.js";
const cssPath = "src/styles/common.css";
const plainCss = "body { margin: 0; }\n";

const siteFiles = {
  "gatsby-config.js": `module.exports = { plugins: [
    { resolve: "gatsby-source-filesystem", options: { name: "src", path: \`\${__dirname}/src/\` } },
    { resolve: "gatsby-transformer-remark", options: { plugins: [] } },
    "gatsby-plugin-styled-components",
  ] };`,
  [cssPath]: plainCss,
  "src/styles/palette.js": 'export default { lettering: "#125078" };',
  "src/components/PageTheme.js": `import React from "react";
    import styled, { ThemeProvider } from "styled-components";
    import palette from "../styles/palette";
    import "../styles/common.css";

    const Canvas = styled.div\`display: block;\`;
    const PageTheme = ({ children }) => (
      <ThemeProvider theme={palette}><Canvas>{children}</Canvas></ThemeProvider>
    );
    export default PageTheme;`,
  [cardPath]: `import React from "react";
    import styled from "styled-components";

    const ArtFrame = styled.div\`
      width: 96px;
      height: 72px;
      flex-shrink: 0;
      & img { max-width: 100%; max-height: 100%; }
    \`;
    const Caption = styled.span\`color: \${props => props.theme.lettering};\`;
    const IllustratedCard = () => (
      <section>
        <ArtFrame><img src="/artwork.png" alt="Mountain" /></ArtFrame>
        <Caption>Mountain</Caption>
      </section>
    );
    export default IllustratedCard;`,
  "src/layouts/index.js": `import React from "react";
    import PageTheme from "../components/PageTheme";
    const Layout = ({ children }) => <PageTheme>{children()}</PageTheme>;
    export default Layout;`,
  "src/pages/index.js": `import React from "react";
    import IllustratedCard from "../components/IllustratedCard";
    const CatalogPage = () => <main><IllustratedCard /></main>;
    export default CatalogPage;`,
};

const write = (filename: string, body: string) => {
  fs.mkdirSync(path.dirname(filename), { recursive: true });
  fs.writeFileSync(filename, body);
};

const writeOfflineSite = (directory: string): void => {
  const dependencyParents = new Map(Object.entries(contract.dependencyParents));
  const directDependencies: Record<string, string> = {};
  const lockBlocks = [
    "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1",
  ];

  for (const [name, [version, digest]] of Object.entries(contract.releases)) {
    if (!version || !digest) throw new Error(`Missing registry release for ${name}`);
    const parent = dependencyParents.get(name);
    if (!parent) directDependencies[name] = version;
    const record = [
      `${name}@${parent?.range ?? version}:`,
      `  version "${version}"`,
      `  resolved "https://registry.npmjs.org/${name}/-/${name}-${version}.tgz#${digest}"`,
    ];
    const children = [...dependencyParents].filter(([, edge]) => edge.name === name);
    if (children.length > 0) {
      record.push("  dependencies:");
      for (const [child, edge] of children) {
        record.push(`    ${child} "${edge.range}"`);
      }
    }
    lockBlocks.push(record.join("\n"));
  }

  write(
    path.join(directory, "package.json"),
    JSON.stringify({
      name: "illustrated-catalogue",
      private: true,
      dependencies: directDependencies,
    }),
  );
  write(path.join(directory, "yarn.lock"), lockBlocks.join("\n\n") + "\n");
  for (const [relative, body] of Object.entries(siteFiles)) {
    write(path.join(directory, relative), body);
  }
};

describe("Gatsby v1 styled image reservation in an offline source scan", () => {
  it.each(["curated", "upstream"] as const)(
    "rechecks the declared route after same-process filesystem edits in %s mode",
    (portedRuleMode) => {
      const fixture = fs.mkdtempSync(
        path.join(fs.realpathSync.native(os.tmpdir()), "rd-offline-img-"),
      );
      try {
        const website = path.join(fixture, "website");
        writeOfflineSite(website);
        const filename = path.join(website, cardPath);
        const source = siteFiles[cardPath];
        const inspect = (target: string, rootDirectory = website) => {
          const result = runRule(noImgWithoutDimensions, source, {
            filename: target,
            forceJsx: true,
            includeLocations: true,
            settings: {
              "react-doctor": {
                capabilities: ["react"],
                reactMajorVersion: 18,
                rootDirectory,
                portedRuleMode,
              },
            },
          });
          expect(result.parseErrors).toEqual([]);
          return result.diagnostics;
        };
        const unconfigured = path.join(fixture, "unconfigured.js");
        write(unconfigured, source);
        const warning = inspect(unconfigured, fixture);
        expect(warning).toHaveLength(1);

        expect(fs.existsSync(path.join(website, "node_modules"))).toBe(false);
        expect(inspect(filename)).toEqual([]);

        const commonCss = path.join(website, cssPath);
        write(commonCss, "img { width: auto; height: auto; max-width: none; }\n");
        expect(inspect(filename)).toEqual(warning);
        write(commonCss, plainCss);
        expect(inspect(filename)).toEqual([]);

        const babelConfig = path.join(fixture, ".babelrc");
        write(babelConfig, '{"plugins":["custom-transform"]}');
        expect(inspect(filename)).toEqual(warning);
        fs.rmSync(babelConfig);
        expect(inspect(filename)).toEqual([]);

        const nearbyModules = path.join(website, "src", "components", "node_modules");
        write(
          path.join(nearbyModules, "styled-components", "package.json"),
          '{"name":"styled-components","version":"3.3.2"}',
        );
        expect(inspect(filename)).toEqual(warning);
        fs.rmSync(nearbyModules, { recursive: true });
        expect(inspect(filename)).toEqual([]);

        const pageFilename = path.join(website, "src/pages/index.js");
        write(
          pageFilename,
          `${siteFiles["src/pages/index.js"]}
          const reset = self.document.createElement("style");
          reset.textContent = "div { width: auto !important; height: auto !important; }";
          self.document.head.appendChild(reset);`,
        );
        expect(inspect(filename)).toEqual(warning);
        write(pageFilename, siteFiles["src/pages/index.js"]);
        expect(inspect(filename)).toEqual([]);

        const additionalPage = path.join(website, "src/pages/build/alternate.js");
        write(
          additionalPage,
          `import React from "react";
          import IllustratedCard from "../../components/IllustratedCard";
          const AlternatePage = () => <IllustratedCard />;
          export default AlternatePage;`,
        );
        expect(inspect(filename)).toEqual(warning);
        fs.rmSync(additionalPage);
        expect(inspect(filename)).toEqual([]);

        const ambientModules = path.join(fixture, "ambient");
        const originalNodePath = process.env.NODE_PATH;
        try {
          fs.mkdirSync(ambientModules);
          process.env.NODE_PATH = originalNodePath
            ? [originalNodePath, ambientModules].join(path.delimiter)
            : ambientModules;
          expect(inspect(filename)).toEqual([]);
          const pluginFile = path.join(ambientModules, "babel-plugin-styled-components.js");
          write(pluginFile, "module.exports = () => ({});");
          expect(inspect(filename)).toEqual(warning);
          fs.rmSync(pluginFile);
          expect(inspect(filename)).toEqual([]);
        } finally {
          if (originalNodePath === undefined) delete process.env.NODE_PATH;
          else process.env.NODE_PATH = originalNodePath;
        }
      } finally {
        fs.rmSync(fixture, { force: true, recursive: true });
      }
    },
  );
});
