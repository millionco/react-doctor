import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { describe, expect, it } from "vite-plus/test";
import { runRule } from "../../../test-utils/run-rule.js";
import { wrapWithSemanticContext } from "../../utils/wrap-with-semantic-context.js";
import { effectNeedsCleanup } from "./effect-needs-cleanup.js";

// Entirely authored source: the lock text describes the supported declared build;
// it is not an installation or evidence that an executable ran.
const source = `import { useEffect } from "react";
import { events } from "./events";
export function Panel() {
  useEffect(() => {
    const close = () => {};
    for (const event of events) window.addEventListener(event, close);
    return () => {
      for (const event of events) window.removeEventListener(event, close);
    };
  }, []);
  return <div />;
}`;

interface IterableCleanupCase {
  readonly name: string;
  readonly changes: Readonly<Record<string, string>>;
  readonly expected: number;
}

const cases: ReadonlyArray<IterableCleanupCase> = [
  {
    name: "a visible compiler entry differs from the declared stock package",
    changes: {
      "node_modules/esbuild/package.json": JSON.stringify({
        name: "esbuild",
        version: "0.15.13",
        main: "lib/main.js",
      }),
      "node_modules/esbuild/lib/main.js": `module.exports = { build: () => {} };`,
    },
    expected: 1,
  },
  {
    name: "qualified global iterator changes the event between setup and cleanup",
    changes: {
      "src/iterator-override.ts": `let iteration = 0;
const key = "Array";
globalThis[key].prototype[globalThis.Symbol.iterator] = function* () {
  yield ++iteration === 1 ? "resize" : "scroll";
};`,
    },
    expected: 1,
  },
  {
    name: "array prototype is reached through reflection",
    changes: {
      "src/iterator-override.ts": `const prototype = Object.getPrototypeOf([]);
const key = Object.getOwnPropertySymbols(prototype)[0];
prototype[key] = function* () { yield "wheel"; };`,
    },
    expected: 1,
  },
  { name: "declared stock build with private primitive list", changes: {}, expected: 0 },
  {
    name: "sibling namespace alias mutates list",
    changes: {
      "src/consumer.ts": `import * as constants from "./events";
const alias = constants.events; alias.push("wheel");`,
    },
    expected: 1,
  },
  {
    name: "mutable producer binding",
    changes: {
      "src/events.ts": `export let events = ["resize", "scroll"];`,
    },
    expected: 1,
  },
  {
    name: "alternate extension can retarget import",
    changes: {
      "src/events.js": `export const events = ["wheel"];`,
    },
    expected: 1,
  },
  {
    name: "public list escape from entry",
    changes: {
      "src/index.ts": `export { Panel } from "./Panel"; export { events } from "./events";`,
    },
    expected: 1,
  },
  {
    name: "shape conforming local compiler substitution",
    changes: {
      "node_modules/tsup/package.json": JSON.stringify({
        name: "tsup",
        version: "6.4.0",
        bin: { tsup: "dist/cli-default.js" },
      }),
      "node_modules/tsup/dist/cli-default.js": `throw new Error("authored substituted provider; never executed");`,
    },
    expected: 1,
  },
];

describe("effect-needs-cleanup private imported primitive iterable", () => {
  it.each(cases)("$name", ({ changes, expected }) => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), "private-iterable-test-"));
    try {
      const files: Record<string, string> = {
        "package.json": JSON.stringify({
          name: "authored-private-iterable",
          version: "1.0.0",
          main: "dist/index.js",
          module: "dist/index.mjs",
          files: ["dist"],
          exports: { ".": { import: "./dist/index.mjs", require: "./dist/index.js" } },
          scripts: { build: "tsup" },
          devDependencies: { tsup: "6.4.0" },
          dependencies: { react: "18.3.1" },
        }),
        "tsconfig.json": JSON.stringify({ compilerOptions: { jsx: "react-jsx" } }),
        "tsup.config.ts": `import { defineConfig } from "tsup";
export default defineConfig({ entry: ["src/index.ts"], format: ["cjs", "esm"], clean: true });`,
        "yarn.lock": `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

tsup@6.4.0:
  version "6.4.0"
  resolved "https://registry.yarnpkg.com/tsup/-/tsup-6.4.0.tgz#d860955c5b248a61959a97dbae5e0365129b9fa4"
  integrity sha512-4OlbqIK/SF+cJp0mMqPM2pKULvgj/1S2Gm3I1aFoFGIryUOyIqPZBoqKkqVQT6uFtWJ5AHftIv0riXKfHox1zQ==

esbuild@^0.15.1:
  version "0.15.13"
  resolved "https://registry.yarnpkg.com/esbuild/-/esbuild-0.15.13.tgz#7293480038feb2bafa91d3f6a20edab3ba6c108a"
  integrity sha512-Cu3SC84oyzzhrK/YyN4iEVy2jZu5t2fz66HEOShHURcjSkOSAVL8C/gfUT+lDJxkVHpg8GZ10DD0rMHRPqMFaQ==
`,
        "src/index.ts": `export { Panel } from "./Panel";`,
        "src/events.ts": `export const events = ["resize", "scroll"];`,
        "src/Panel.tsx": source,
        ...changes,
      };
      for (const [relative, content] of Object.entries(files)) {
        const filename = path.join(root, relative);
        fs.mkdirSync(path.dirname(filename), { recursive: true });
        fs.writeFileSync(filename, content);
      }
      const result = runRule(wrapWithSemanticContext(effectNeedsCleanup), source, {
        filename: path.join(root, "src/Panel.tsx"),
      });
      expect(result.parseErrors).toEqual([]);
      expect(result.diagnostics).toHaveLength(expected);
    } finally {
      fs.rmSync(root, { recursive: true, force: true });
    }
  });
});
