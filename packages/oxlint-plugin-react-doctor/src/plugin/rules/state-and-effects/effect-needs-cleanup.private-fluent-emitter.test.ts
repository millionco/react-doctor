interface FluentCleanupCase {
  readonly name: string;
  readonly changes: Readonly<Record<string, string>>;
  readonly expected: number;
}

const cases: ReadonlyArray<FluentCleanupCase> = [
  { name: "private emitter through an internal barrel", changes: {}, expected: 0 },
  {
    name: "public re-export through an internal barrel",
    changes: { "src/index.ts": 'export { registry as publicRegistry } from "./barrel";' },
    expected: 1,
  },
  {
    name: "public method returns the emitter instead of discarding it",
    changes: {
      "src/public.ts": `import { registry } from "./barrel";
export function announce(value: unknown) { return registry.emit("visible", value); }`,
    },
    expected: 1,
  },
  {
    name: "setup stores a bound copy of the handler",
    changes: {
      "src/registry.ts": provider.replace(
        "new Set([handler])",
        "new Set([handler.bind(undefined)])",
      ),
    },
    expected: 1,
  },
  {
    name: "different Map keys for numeric and string event names",
    changes: { "src/Panel.tsx": panel.replace("off(Signal.Reset, reset)", 'off("0", reset)') },
    expected: 1,
  },
  {
    name: "project code changes Set deletion",
    changes: {
      "src/changed-set.ts": "globalThis.Set.prototype.delete = () => false;",
      "src/index.ts": `import "./changed-set";\n${stockPackageFiles["src/index.ts"]}`,
    },
    expected: 1,
  },
];

describe("effect-needs-cleanup private fluent emitter", () => {
  it.each(cases)("$name", ({ changes, expected }) => {
    const fixture = fs.mkdtempSync(path.join(os.tmpdir(), "private-fluent-emitter-"));
    try {
      const files = { ...stockPackageFiles, ...changes };
      for (const [relative, content] of Object.entries(files)) {
        const filename = path.join(fixture, relative);
        fs.mkdirSync(path.dirname(filename), { recursive: true });
        fs.writeFileSync(filename, content);
      }
      const result = runRule(wrapWithSemanticContext(effectNeedsCleanup), files["src/Panel.tsx"]!, {
        filename: path.join(fixture, "src/Panel.tsx"),
      });
      expect(result.parseErrors).toEqual([]);
      expect(result.diagnostics).toHaveLength(expected);
    } finally {
      fs.rmSync(fixture, { recursive: true, force: true });
    }
  });
});
