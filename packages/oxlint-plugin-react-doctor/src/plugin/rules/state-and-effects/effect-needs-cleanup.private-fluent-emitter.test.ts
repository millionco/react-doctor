const panel = `import { useEffect } from "react";
import { registry } from "./barrel";
import { Signal } from "./signal";
export function Panel({ id }: { id: string }) {
  function receive() {}
  function reset() {}
  useEffect(() => {
    registry.on(id, receive).on(Signal.Reset, reset);
    return () => { registry.off(id, receive).off(Signal.Reset, reset); };
  }, [id]);
  return <div />;
}
`;

const provider = `type Handler = (value: unknown) => void;
function makeRegistry() {
  const entries = new Map<string | number, Set<Handler>>();
  return {
    on(key: string | number, handler: Handler) {
      entries.has(key) ? entries.get(key)!.add(handler) : entries.set(key, new Set([handler]));
      return this;
    },
    off(key: string | number, handler: Handler) {
      entries.has(key) && entries.get(key)!.delete(handler);
      return this;
    },
    emit(key: string | number, value: unknown) {
      entries.has(key) && entries.get(key)!.forEach((handler) => { handler(value); });
      return this;
    },
  };
}
export const registry = makeRegistry();
`;

