import { describe, expect, it } from "vite-plus/test";
import { hasReviewedQueryClientAndNextIntlYarnLock } from "./has-reviewed-query-client-and-next-intl-yarn-lock.js";

const DIRECT_RANGES = { reactQueryRange: "^5.71.10", nextIntlRange: "^4.0.2" };

const REVIEWED_LOCK = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

"@tanstack/query-core@5.71.10":
  version "5.71.10"
  resolved "https://registry.yarnpkg.com/@tanstack/query-core/-/query-core-5.71.10.tgz#1f2dc5abf595156e7d9c5d6e4f47e805a7083c30"
  integrity sha512-/fKEY8fO1nbszfrBatzmhJa1nEwIKn0c6Tv2A1ocSA5OiD2GukOIV8nnBbvJRgZb/VIoBy9/N4PVbABI8YQLow==

"@tanstack/react-query@^5.71.10":
  version "5.71.10"
  resolved "https://registry.yarnpkg.com/@tanstack/react-query/-/react-query-5.71.10.tgz#940d485a499b86aaa37764e26709ed79b393fe29"
  integrity sha512-mQYM/ObpL8YMDz8vCoUuHkbe8Yu7NnVRH8aBaBa/3zlufjp1f1VuWjeO3TcumNHfuVMDwEAGinsgwrB7OKADiQ==
  dependencies:
    "@tanstack/query-core" "5.71.10"

next-intl@^4.0.2:
  version "4.0.2"
  resolved "https://registry.yarnpkg.com/next-intl/-/next-intl-4.0.2.tgz#952cb392e441c4feedc78d158a27c5d3c1d24991"
  integrity sha512-3cKVflwdrqxCOvAL+DtGN68qR802i0PEj0dttkAD5IK5XxOjugQs4yU8aSakvPMbkOrhEJ+89z5lG2EAqi7Gkw==
  dependencies:
    "@formatjs/intl-localematcher" "^0.5.4"
    negotiator "^1.0.0"
    use-intl "^4.0.2"

next@15.2.4:
  version "15.2.4"
  resolved "https://registry.yarnpkg.com/next/-/next-15.2.4.tgz#e05225e9511df98e3b2edc713e17f4c970bff961"
  integrity sha512-VwL+LAaPSxEkd3lU2xWbgEOtrM8oedmyhBqaVNmgKB+GvZlCy9rgaEc+y2on0wv+l0oSFqLtYD6dcC1eAedUaQ==

react@^19.0.0:
  version "19.1.0"
  resolved "https://registry.yarnpkg.com/react/-/react-19.1.0.tgz#926864b6c48da7627f004795d6cce50e90793b75"
  integrity sha512-FS+XFBNvn3GTAWq26joslQgWNoFu08F4kl0J4CgdNKADkdSGXQyTCnKteIAJy96Br6YbpEU1LSzV5dYtjMkMDg==
`;

const hasReviewedLock = (lockText: string): boolean =>
  hasReviewedQueryClientAndNextIntlYarnLock(lockText, DIRECT_RANGES);

describe("hasReviewedQueryClientAndNextIntlYarnLock", () => {
  it("matches the reviewed resolutions and the exact transitive edge", () => {
    expect(hasReviewedLock(REVIEWED_LOCK)).toBe(true);
    expect(hasReviewedLock(REVIEWED_LOCK.replaceAll("\n", "\r\n"))).toBe(true);
  });

  it("reads grouped selectors including a quoted range with a comma", () => {
    const groupedLock = REVIEWED_LOCK.replace(
      '"@tanstack/react-query@^5.71.10":',
      '"@tanstack/react-query@>=5.71.10, <5.72.0", "@tanstack/react-query@^5.71.10":',
    ).replace("next-intl@^4.0.2:", 'next-intl@4.0.2, "next-intl@^4.0.2":');
    expect(hasReviewedLock(groupedLock)).toBe(true);
    expect(
      hasReviewedQueryClientAndNextIntlYarnLock(groupedLock, {
        ...DIRECT_RANGES,
        nextIntlRange: "4.0.2",
      }),
    ).toBe(true);
  });

  it("requires the direct selector and rejects package alias ranges", () => {
    expect(
      hasReviewedQueryClientAndNextIntlYarnLock(REVIEWED_LOCK, {
        ...DIRECT_RANGES,
        reactQueryRange: "5.71.10",
      }),
    ).toBe(false);
    expect(
      hasReviewedQueryClientAndNextIntlYarnLock(REVIEWED_LOCK, {
        ...DIRECT_RANGES,
        nextIntlRange: "npm:next-intl@^4.0.2",
      }),
    ).toBe(false);
  });

  it.each([
    ["non-v1 format", REVIEWED_LOCK.replace("yarn lockfile v1", "yarn lockfile v2")],
    ["wrong registry", REVIEWED_LOCK.replace("registry.yarnpkg.com", "registry.example.org")],
    ["wrong version", REVIEWED_LOCK.replace('version "5.71.10"', 'version "5.71.11"')],
    ["wrong integrity", REVIEWED_LOCK.replace("sha512-mQYM", "sha512-nQYM")],
    ["wrong Next integrity", REVIEWED_LOCK.replace("sha512-VwL+", "sha512-AwL+")],
    ["wrong React integrity", REVIEWED_LOCK.replace("sha512-FS+X", "sha512-AS+X")],
    [
      "different query-core selector",
      REVIEWED_LOCK.replace(
        '"@tanstack/query-core" "5.71.10"',
        '"@tanstack/query-core" "~5.71.10"',
      ),
    ],
    [
      "optional transitive edge",
      REVIEWED_LOCK.replace("  dependencies:", "  optionalDependencies:"),
    ],
    [
      "duplicate mandatory and optional dependency",
      REVIEWED_LOCK.replace(
        '    "@tanstack/query-core" "5.71.10"',
        '    "@tanstack/query-core" "5.71.10"\n  optionalDependencies:\n    "@tanstack/query-core" "5.71.10"',
      ),
    ],
    [
      "duplicate selector in grouped header",
      REVIEWED_LOCK.replace(
        '"@tanstack/react-query@^5.71.10":',
        '"@tanstack/react-query@^5.71.10", "@tanstack/react-query@^5.71.10":',
      ),
    ],
    [
      "second stanza with an escaped spelling of the same selector",
      `${REVIEWED_LOCK}\n${String.raw`"\u006eext-intl@^4.0.2":`}\n  version "4.0.3"\n`,
    ],
    [
      "duplicate version field",
      REVIEWED_LOCK.replace('version "4.0.2"', 'version "4.0.2"\n  version "4.0.3"'),
    ],
    [
      "malformed quoted header",
      REVIEWED_LOCK.replace('"@tanstack/query-core@', '""@tanstack/query-core@'),
    ],
    ["truncated stanza", `${REVIEWED_LOCK}\nunused@^1.0.0:\n`],
  ])("rejects %s", (_reason, lockText) => {
    expect(hasReviewedLock(lockText)).toBe(false);
  });
});
