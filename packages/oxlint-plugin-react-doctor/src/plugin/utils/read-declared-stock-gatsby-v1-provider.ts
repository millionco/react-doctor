import * as fs from "node:fs";
import { createRequire } from "node:module";
import * as path from "node:path";
import { STOCK_GATSBY_MAX_CONFIG_BYTES } from "../constants/design.js";
import { recordContentProbe, recordExistenceProbe } from "./cross-file-probe-recorder.js";
import contract from "./declared-gatsby-v1-provider-contract.json";

interface YarnLockRecord {
  readonly version: string;
  readonly resolved: string;
  readonly dependencies: ReadonlyMap<string, string>;
}

const readPlainFile = (filename: string): string | null => {
  recordExistenceProbe(filename);
  recordContentProbe(filename);
  const stat = fs.lstatSync(filename, { throwIfNoEntry: false });
  if (
    !stat?.isFile() ||
    stat.size > STOCK_GATSBY_MAX_CONFIG_BYTES ||
    fs.realpathSync.native(filename) !== filename
  )
    return null;
  return fs.readFileSync(filename, "utf8");
};

const parseSelectors = (input: string): string[] | null => {
  const selectors: string[] = [];
  let remaining = input;
  while (remaining.length > 0) {
    const match = /^(?:"([^"\\]+)"|([^",\s]+))(?:,\s+|$)/u.exec(remaining);
    if (!match) return null;
    selectors.push(match[1] ?? match[2]!);
    remaining = remaining.slice(match[0].length);
  }
  return selectors.length > 0 ? selectors : null;
};

const readYarnV1Records = (input: string): ReadonlyMap<string, YarnLockRecord> | null => {
  if (
    !/^# THIS IS AN AUTOGENERATED FILE\. DO NOT EDIT THIS FILE DIRECTLY\.\r?\n# yarn lockfile v1(?:\r?\n|$)/u.test(
      input,
    )
  )
    return null;
  const records = new Map<string, YarnLockRecord>();
  for (const block of input.trimEnd().split(/\r?\n\s*\r?\n/u)) {
    if (!block || block.startsWith("#")) continue;
    const [header, versionLine, resolvedLine, ...fields] = block.split(/\r?\n/u);
    if (!header?.endsWith(":")) return null;
    const selectors = parseSelectors(header.slice(0, -1));
    const version = /^  version "([^"\r\n]+)"$/u.exec(versionLine ?? "")?.[1];
    const resolved = /^  resolved "([^"\r\n]+)"$/u.exec(resolvedLine ?? "")?.[1];
    if (!selectors || !version || !resolved) return null;
    const dependencies = new Map<string, string>();
    let withinDependencies = false;
    for (const line of fields) {
      if (!line.startsWith("    ")) {
        withinDependencies = line === "  dependencies:";
        continue;
      }
      if (!withinDependencies) continue;
      const property = /^    (?:"([^"\\]+)"|([^"\s]+)) "([^"\\]+)"$/u.exec(line);
      if (!property) return null;
      const name = property[1] ?? property[2]!;
      if (dependencies.has(name)) return null;
      dependencies.set(name, property[3]!);
    }
    for (const selector of selectors) {
      if (records.has(selector)) return null;
      records.set(selector, { version, resolved, dependencies });
    }
  }
  return records;
};

const isRecord = (value: unknown): value is Record<string, unknown> =>
  value !== null && typeof value === "object" && !Array.isArray(value);

const hasNoOfflineModuleRoot = (startingDirectory: string, visited: Set<string>): boolean => {
  let directory = startingDirectory;
  while (!visited.has(directory)) {
    visited.add(directory);
    for (const name of ["node_modules", ".pnp.cjs", ".pnp.js", ".yarnrc", ".yarnrc.yml"]) {
      const filename = path.join(directory, name);
      recordExistenceProbe(filename);
      if (fs.lstatSync(filename, { throwIfNoEntry: false })) return false;
    }
    const manifestPath = path.join(directory, "package.json");
    recordExistenceProbe(manifestPath);
    if (fs.lstatSync(manifestPath, { throwIfNoEntry: false })) {
      const manifest = readPlainFile(manifestPath);
      if (!manifest) return false;
      const data: unknown = JSON.parse(manifest);
      if (
        !isRecord(data) ||
        ["workspaces", "resolutions", "overrides"].some((key) => Object.hasOwn(data, key))
      )
        return false;
    }
    const parent = path.dirname(directory);
    if (directory === parent) return true;
    directory = parent;
  }
  return true;
};

const hasAmbientStyledBabelPlugin = (siteRoot: string): boolean => {
  const requireFromSite = createRequire(path.join(siteRoot, "package.json"));
  const roots = new Set([
    ...(requireFromSite.resolve.paths(contract.supplementalBabelPlugin) ?? []),
    ...(process.env.NODE_PATH ?? "").split(path.delimiter).filter(Boolean),
  ]);
  for (const root of roots) {
    if (!path.isAbsolute(root)) return true;
    const base = path.join(root, contract.supplementalBabelPlugin);
    for (const candidate of [base, base + ".js", base + ".json", base + ".node"]) {
      recordExistenceProbe(candidate);
      if (fs.lstatSync(candidate, { throwIfNoEntry: false })) return true;
    }
  }
  return false;
};

/** Checks the configured, declared stock route for an offline source scan. */
export const readDeclaredStockGatsbyV1Provider = (
  siteRoot: string,
  pluginNames: ReadonlyArray<string>,
  sourceFiles: ReadonlyArray<string>,
): ReadonlyMap<string, string> | null => {
  try {
    if (
      !path.isAbsolute(siteRoot) ||
      fs.realpathSync.native(siteRoot) !== siteRoot ||
      hasAmbientStyledBabelPlugin(siteRoot)
    )
      return null;
    const visited = new Set<string>();
    if (
      !hasNoOfflineModuleRoot(siteRoot, visited) ||
      !hasNoOfflineModuleRoot(path.join(siteRoot, ".cache"), visited)
    )
      return null;
    for (const file of sourceFiles) {
      const relative = path.relative(siteRoot, file);
      if (
        !path.isAbsolute(file) ||
        relative.startsWith(`..${path.sep}`) ||
        relative === ".." ||
        path.isAbsolute(relative) ||
        !hasNoOfflineModuleRoot(path.dirname(file), visited)
      )
        return null;
    }
    const manifestBody = readPlainFile(path.join(siteRoot, "package.json"));
    const lock = readPlainFile(path.join(siteRoot, "yarn.lock"));
    if (!manifestBody || !lock) return null;
    const manifest: unknown = JSON.parse(manifestBody);
    const indexed = readYarnV1Records(lock);
    if (!isRecord(manifest) || !isRecord(manifest.dependencies) || !indexed) return null;
    if (pluginNames.some((name) => !Object.hasOwn(contract.releases, name))) return null;
    const rows = new Map<string, YarnLockRecord>();
    const direct = new Map(Object.entries(manifest.dependencies));
    const transitive: Record<string, { name: string; range: string }> = contract.dependencyParents;
    const packageNames = new Set(Object.keys(contract.releases));
    if (
      [...direct.keys()].some((name) => !packageNames.has(name) || Object.hasOwn(transitive, name))
    )
      return null;
    for (const field of ["optionalDependencies", "peerDependencies", "devDependencies"]) {
      const extras = manifest[field];
      if (
        extras !== undefined &&
        (!isRecord(extras) || Object.keys(extras).some((name) => packageNames.has(name)))
      )
        return null;
    }
    for (const [name, [version, digest]] of Object.entries(contract.releases)) {
      const parent = transitive[name];
      if (
        parent &&
        (direct.has(name) || rows.get(parent.name)?.dependencies.get(name) !== parent.range)
      )
        return null;
      const range = parent?.range ?? direct.get(name);
      if (typeof range !== "string" || digest === undefined) return null;
      const selected = indexed.get(`${name}@${range}`);
      const suffix = `/${name}/-/${name}-${version}.tgz#${digest}`;
      if (
        selected?.version !== version ||
        !["https://registry.yarnpkg.com", "https://registry.npmjs.org"].some(
          (registry) => selected.resolved === registry + suffix,
        )
      )
        return null;
      rows.set(name, selected);
    }
    const optionalBabelName = contract.supplementalBabelPlugin;
    if ([...indexed.keys()].some((key) => key.startsWith(optionalBabelName + "@"))) return null;
    return new Map([...rows].map(([name, record]) => [name, record.version]));
  } catch {
    return null;
  }
};
